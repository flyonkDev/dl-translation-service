/**
 * Цепочки языков Tesseract (ISO 639-3 коды через +) по странам ISO 3166-1 alpha-2.
 * Для страны не из карты используется fallback в country-registry.
 *
 * Порядок в массиве = порядок попыток каскада (сначала наиболее вероятный OCR).
 */

function batch(
  codes: readonly string[],
  langs: readonly string[],
): Record<string, string[]> {
  return Object.fromEntries(codes.map((c) => [c, [...langs]]))
}

